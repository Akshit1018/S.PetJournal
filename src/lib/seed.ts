function series(
  petId: string,
  key: string,
  unit: string,
  points: Array<[string, number]>,
): MetricSample[] {
  return points.map(([at, value], i) => ({
    id: `${petId}_${key}_${i}`,
    petId,
    key,
    value,
    unit,
    at: T(at),
  }));
}

